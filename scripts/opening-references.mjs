// Requires ImageMagick. Rebuild after changing these reviewed photographic portraits.
// Emits the fixed manifest the edge function trusts, and stages the exact JPEG bytes for
// upload to the private "opening-references" bucket. Bucket contents must match the manifest.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
// Use the same public cast-file registry as casting, including mixed-film selections.
const catalog = readFileSync('src/types/gameData.ts', 'utf8');
const finalGirls = new Set([...catalog.matchAll(/finalGirls: *\[([^\]]+)\]/g)].flatMap(([,names])=>[...names.matchAll(/'([^']+)'/g)].map(([,name])=>name)));
const registry = catalog.split('const CHARACTER_FILES:')[1].split('};')[0];
const portraits = Object.fromEntries([...registry.matchAll(/'([^']+)': '([^']+)[.]png'/g)].filter(([,name])=>finalGirls.has(name) || ['Billy the Bear','Inkanyamba','Poltergeist'].includes(name)).map(([,name,file])=>[name,file]));
const slug = name => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const stage = 'build/opening-references';
rmSync(stage, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });
const entries = {};
const hashes = [];
for (const [name, file] of Object.entries(portraits)) {
  const source = `src/assets/characters/ai/${file}.png`;
  const bytes = execFileSync('magick', [source, '-auto-orient', '-resize', '768x768>', '-strip', '-quality', '90', 'jpeg:-']);
  const path = `${slug(name)}.jpg`;
  writeFileSync(`${stage}/${path}`, bytes);
  entries[name] = { path, sha256: createHash('sha256').update(bytes).digest('hex') };
  hashes.push(`// ${file}.png SHA-256: ${createHash('sha256').update(readFileSync(source)).digest('hex')}`);
}
writeFileSync('supabase/functions/_shared/openingReferenceManifest.ts',
  `// Generated by scripts/opening-references.mjs. Existing artwork, no new image generation.\n// Fixed object keys inside the private "opening-references" bucket; callers never supply paths.\n// sha256 is of the exact JPEG bytes stored there — the loader refuses any other bytes.\n${hashes.join('\n')}\nexport const OPENING_REFERENCE_MANIFEST: Record<string, { path: string; sha256: string }> = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`Staged ${Object.keys(entries).length} photographic identity references in ${stage}/ for upload to the opening-references bucket.`);
