// Requires ImageMagick. Rebuild after changing these reviewed photographic portraits.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const portraits = { 'Billy the Bear': 'billy-the-bear', Gwynn: 'gwynn', Rena: 'rena' };
const images = {};
const hashes = [];
for (const [name, file] of Object.entries(portraits)) {
  const source = `src/assets/characters/ai/${file}.png`;
  const bytes = execFileSync('magick', [source, '-auto-orient', '-resize', '768x768>', '-strip', '-quality', '90', 'jpeg:-']);
  images[name] = `data:image/jpeg;base64,${bytes.toString('base64')}`;
  hashes.push(`// ${file}.png SHA-256: ${createHash('sha256').update(readFileSync(source)).digest('hex')}`);
}
writeFileSync('supabase/functions/_shared/openingReferenceData.ts',
  `// Generated by scripts/opening-references.mjs. Existing artwork, no new image generation.\n// Embedded like poster fonts so deployment needs no static-file configuration.\n${hashes.join('\n')}\nexport const OPENING_REFERENCE_DATA: Record<string, string> = ${JSON.stringify(images, null, 2)};\n`);
console.log(`Bundled ${Object.keys(images).length} photographic identity references.`);
