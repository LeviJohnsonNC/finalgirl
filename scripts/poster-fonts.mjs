// Build the renderer's static ASCII font subsets. Runtime never fetches a font.
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const root = new URL('../supabase/functions/_shared/', import.meta.url);
const pin = '9862abc066c9b83bf84c3e8ed1fc2d8d48f9bbf0';
const sources = [
  ['slash','ofl/sedgwickavedisplay','SedgwickAveDisplay-Regular.ttf','OFL.txt'],
  ['brush','apache/permanentmarker','PermanentMarker-Regular.ttf','LICENSE.txt'],
  ['gothic','ofl/metalmania','MetalMania-Regular.ttf','OFL.txt'],
  ['industrial','ofl/blackopsone','BlackOpsOne-Regular.ttf','OFL.txt'],
];
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const directory = mkdtempSync(join(tmpdir(),'poster-fonts-'));
const fonts = {}, manifest = [];
for (const [key, folder, file, license] of sources) {
  const url = `https://raw.githubusercontent.com/google/fonts/${pin}/${folder}/`;
  const response = await fetch(url + file), licenseResponse = await fetch(url + license);
  if (!response.ok || !licenseResponse.ok) throw new Error('Cannot load pinned font: ' + key);
  const original = Buffer.from(await response.arrayBuffer()), source = join(directory,key+'.ttf'), target = join(directory,key+'-ascii.ttf');
  writeFileSync(source, original);
  execFileSync(process.env.POSTER_FONT_TOOL || 'pyftsubset', [source, '--unicodes=U+0020-007E', '--layout-features=kern,liga', '--no-hinting', '--notdef-glyph', '--notdef-outline', '--recommended-glyphs', '--name-IDs=0,1,2,3,4,5,6,13,14', '--name-languages=*', '--no-recalc-timestamp', '--output-file='+target]);
  const subset = readFileSync(target);
  if (subset.length > 128*1024) throw new Error('Font exceeds subset budget: '+key);
  fonts[key] = subset.toString('base64');
  const sourceLicense = Buffer.from(await licenseResponse.arrayBuffer());
  const licenseBytes = Buffer.from(sourceLicense.toString('utf8').replace(/\r\n/g,'\n').replace(/[ \t]+$/gm,''));
  writeFileSync(new URL(`poster-fonts/${key}-LICENSE.txt`,root), licenseBytes);
  manifest.push({ key, source:url+file, sourceSha256:hash(original), sha256:hash(subset), bytes:subset.length,
    license:url+license, sourceLicenseSha256:hash(sourceLicense), licenseSha256:hash(licenseBytes) });
}
writeFileSync(new URL('posterDisplayFonts.ts',root), '// Generated by scripts/poster-fonts.mjs with fonttools 4.61.1. ASCII subsets; see poster-fonts/README.md.\nexport const POSTER_DISPLAY_FONTS = '+JSON.stringify(fonts,null,2)+' as const;\n');
writeFileSync(new URL('poster-fonts/manifest.json',root), JSON.stringify(manifest,null,2)+'\n');
console.log(manifest.map(({key,bytes})=>({key,bytes})));
