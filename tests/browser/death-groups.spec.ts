import {test,expect,activeGame,userId,installTestAudio} from './fixtures';
import {deathFacts,deathSignature} from '../../src/lib/play/death';
import {summarizePlay,type PlayEvent} from '../../src/lib/play/events';
import {openHistory,saveResultOnly} from './play-helpers';
const start:PlayEvent={id:'22222222-2222-4222-8222-222222222222',at:1,kind:'start',saved:0,killed:0,round:4};
const kill:PlayEvent={id:'33333333-3333-4333-8333-333333333333',at:2,kind:'killed',quantity:1,cause:'killer',room:'Cabin'};
const selection={...activeGame.selection,killer:'Dr. Fright'};
const draft={...activeGame,selection,playMode:true,playEvents:[start]};
const log=(page:import('@playwright/test').Page)=>page.evaluate(id=>JSON.parse(localStorage.getItem('final-girl-active-game-v1:'+id)!).playEvents as PlayEvent[],userId);
async function resume(page:import('@playwright/test').Page){await page.goto('/');await page.getByRole('button',{name:'RESUME GAME',exact:true}).click();}

test('one death plus two extra victims survives narration, count corrections, reload and final tally',async({page,archive},info)=>{
 await archive.install(page,{draft});await installTestAudio(page);await resume(page);
 await page.getByRole('button',{name:'Record one victim killed',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Gruesome Death',exact:true});
 // The counter is available before any cause is selected.
 await dialog.getByRole('button',{name:'Add one victim to this death',exact:true}).dblclick();
 await expect(dialog.getByLabel('Victim count',{exact:true})).toHaveText('3');
 expect(summarizePlay(await log(page))).toMatchObject({saved:0,killed:3,round:4});
 await page.screenshot({path:info.outputPath('group-editing.png')});
 await dialog.getByRole('button',{name:'Killer attack',exact:true}).click();
 await dialog.getByRole('button',{name:'Gruesome Death',exact:true}).click();
 await expect(dialog.getByRole('region',{name:'Death scene text',exact:true})).toBeVisible();
 await expect(dialog.locator('.play-death-context')).toContainText('3 victims');
 await expect(dialog.getByRole('group',{name:'Cause of death',exact:true})).toHaveCount(0);
 const id=(await log(page)).find(e=>e.kind==='killed')!.id;
 expect(deathFacts(selection,archive.sessions[0].state.playEvents as PlayEvent[],id)).toMatchObject({quantity:3,round:4});
 await dialog.getByRole('button',{name:'Narrate death scene',exact:true}).click();
 await expect(dialog.getByRole('button',{name:'Stop death narration',exact:true})).toBeVisible();
 await dialog.getByRole('button',{name:'Edit death details',exact:true}).click();
 await expect(dialog.getByRole('button',{name:'Killer attack',exact:true})).toBeVisible();
 await dialog.getByRole('button',{name:'Remove one victim from this death',exact:true}).click();
 await expect(dialog.getByLabel('Victim count',{exact:true})).toHaveText('2');
 await expect(dialog.getByRole('region',{name:'Death scene text',exact:true})).toHaveCount(0);
 expect(await page.evaluate(()=>(window as unknown as {__qaNarrators:{count:()=>number}}).__qaNarrators.count())).toBe(0);
 await dialog.getByRole('button',{name:'Add one victim to this death',exact:true}).click();
 await dialog.getByRole('button',{name:'Read scene',exact:true}).click();
 await expect(dialog.getByRole('region',{name:'Death scene text',exact:true})).toBeVisible();
 expect(archive.calls.filter(c=>c==='generate-death-scene')).toHaveLength(1);
 await page.screenshot({path:info.outputPath('group-reading.png')});
 await dialog.getByRole('button',{name:'Back to game',exact:true}).click();
 await page.reload();await page.getByRole('button',{name:'RESUME GAME',exact:true}).click();
 await expect(page.getByRole('button',{name:'Record one victim killed',exact:true})).toContainText('3');
 expect((await log(page)).filter(e=>e.kind==='killed')).toHaveLength(1);
 await page.getByRole('button',{name:'Finish game',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Won',exact:true}).click();
 await saveResultOnly(page);
 await expect.poll(()=>archive.history.length).toBe(1);
 expect(archive.history[0].victims_killed).toBe(3);
 expect(summarizePlay(archive.history[0].play_events as PlayEvent[]).killed).toBe(3);
});

test('count changes are durable despite close, failed storage, offline sync and AI failure',async({page,archive})=>{
 await archive.install(page,{draft});await resume(page);
 await page.getByRole('button',{name:'Record one victim killed',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Gruesome Death',exact:true});
 await page.evaluate(()=>{const saved=Storage.prototype.setItem; (window as unknown as {restoreStorage:()=>void}).restoreStorage=()=>{Storage.prototype.setItem=saved;};Storage.prototype.setItem=function(key,value){if(key.startsWith('final-girl-active-game-v1:'))throw new Error('quota');saved.call(this,key,value);};});
 await dialog.getByRole('button',{name:'Add one victim to this death',exact:true}).click();
 await expect(dialog.getByRole('alert')).toContainText('count could not be changed');
 await expect(dialog.getByLabel('Victim count',{exact:true})).toHaveText('1');
 await dialog.getByRole('button',{name:'Killer attack',exact:true}).click();
 await dialog.getByRole('textbox',{name:'Death context',exact:true}).fill('A detail that must not be lost.');
 await dialog.getByRole('button',{name:'Gruesome Death',exact:true}).click();
 await expect(dialog.getByRole('alert')).toContainText('Details could not be saved');
 await expect(dialog.getByRole('group',{name:'Cause of death',exact:true})).toBeVisible();
 expect(archive.calls.filter(c=>c==='generate-death-scene')).toHaveLength(0);
 await page.evaluate(()=>(window as unknown as {restoreStorage:()=>void}).restoreStorage());
 await dialog.getByRole('button',{name:'Add one victim to this death',exact:true}).click();
 await expect(dialog.getByLabel('Victim count',{exact:true})).toHaveText('2');
 await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
 await page.getByRole('button',{name:'Latest death scene',exact:true}).click();
 await expect(dialog.getByLabel('Victim count',{exact:true})).toHaveText('2');
 archive.failWrites=true;
 await dialog.getByRole('button',{name:'Gruesome Death',exact:true}).click();
 await expect(dialog.getByRole('status').filter({hasText:'Could not sync'})).toBeVisible();
 expect(archive.calls.filter(c=>c==='generate-death-scene')).toHaveLength(0);
 expect(summarizePlay(await log(page)).killed).toBe(2);
 archive.failWrites=false;archive.failDeaths=true;
 await dialog.getByRole('button',{name:'Gruesome Death',exact:true}).click();
 await expect(dialog.getByRole('status').filter({hasText:'Scene unavailable'})).toBeVisible();
 expect(summarizePlay(await log(page)).killed).toBe(2);
 await dialog.getByRole('button',{name:'Edit death details',exact:true}).click();
 await expect(dialog.getByLabel('Victim count',{exact:true})).toHaveText('2');
});

test('three old Dr. Fright takes reopen freely and allow an explicit dream portrayal rewrite',async({page,archive})=>{
 const events=[start,kill];const facts=deathFacts(selection,events,kill.id)!;
 const legacy=await deathSignature(facts,'legacy');
 archive.deathScenes=[0,1,2].map(take=>({id:`${String(take+1).padStart(8,'0')}-dddd-4ddd-8ddd-dddddddddddd`,session_id:activeGame.id,event_id:kill.id,signature:legacy,take,scene_text:archive.deathText,status:'ready' as const}));
 await archive.install(page,{draft:{...draft,playEvents:events}});await resume(page);
 await page.getByRole('button',{name:'Latest death scene',exact:true}).click();
 await expect(page.getByRole('region',{name:'Death scene text',exact:true})).toBeVisible();
 expect(archive.calls.filter(c=>c==='generate-death-scene')).toHaveLength(0);
 await page.getByRole('button',{name:'Rewrite death',exact:true}).click();
 await expect(page.getByRole('button',{name:'Gruesome Death',exact:true})).toBeEnabled();
 expect(archive.deathScenes).toHaveLength(4);
 expect(archive.deathScenes[3].signature).toBe(await deathSignature(facts));
 await page.getByRole('button',{name:'Back to game',exact:true}).click();
 await openHistory(page);
 await page.getByRole('button',{name:/Undo 1 victim killed at Cabin/}).click();
 await expect(page.getByRole('button',{name:'Latest death scene',exact:true})).toHaveCount(0);
});

